def segment(r):
    high_t = r["Sessions - Total"] > med_s
    high_c = r["Unit Session Percentage"] >= avg_cr
    if high_t and high_c: return "Star"
    if high_t and not high_c: return "Fix"
    if not high_t and high_c: return "Promote"
    return "Review"

